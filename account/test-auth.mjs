import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const home=read('index.html'),auth=read('account/auth.js'),page=read('account/page.js'),config=read('account/config.js'),html=read('account/index.html');
assert.match(home, /href="account\/"/);
assert.match(home, /id="menu"/);
assert.match(home, /WhatsApp/i);
assert.match(html, /data-mode="signup"/);
assert.match(html, /data-mode="recover"/);
assert.match(page, /mode==='update'/);
assert.match(page, /completeAuthFromUrl/);
assert.match(auth, /\/token\?grant_type=password/);
assert.match(auth, /\/token\?grant_type=refresh_token/);
assert.match(auth, /\/recover\?redirect_to=/);
assert.match(auth, /\/signup\?redirect_to=/);
assert.match(auth, /\/user/);
assert.match(auth, /history.replaceState/);
assert.match(config, /sb_publishable_/);
assert.doesNotMatch(config+auth+page, /service_role|sb_secret_/);
console.log('Optional login and guest checkout static checks passed');
